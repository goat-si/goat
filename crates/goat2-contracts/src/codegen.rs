//! Generated artifacts: TypeScript (ts-rs) and JSON Schema (schemars).
//!
//! [render_all] returns `repo-relative path -> contents` for the files this crate owns under
//! `packages/contracts-rs/`. The `generated` integration test compares them with the committed
//! files; `GOAT2_CONTRACTS_BLESS=1 cargo test -p goat2-contracts --test generated` rewrites them
//! (and removes stale files inside the owned directories).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

use schemars::generate::SchemaSettings;
use schemars::transform::RecursiveTransform;
use schemars::{JsonSchema, Schema};
use ts_rs::TS;

use crate::limits;
use crate::*;

/// Generated TypeScript, one file per type plus `index.ts` and `limits.ts`.
pub const TS_DIR: &str = "packages/contracts-rs/src/generated";
/// One JSON Schema per root type, `<Root>.schema.json`.
pub const SCHEMA_DIR: &str = "packages/contracts-rs/schema";
/// Directories the generator owns entirely.
pub const OWNED_DIRS: [&str; 2] = [TS_DIR, SCHEMA_DIR];

/// `repo-relative path -> contents`.
pub type Files = BTreeMap<String, String>;

/// The root types. Each gets a JSON Schema; TypeScript covers them and everything they use.
pub const ROOTS: [&str; 12] = [
    "BotProfile",
    "CardFile",
    "ClientFrame",
    "Fold",
    "HostFrame",
    "LogEvent",
    "LogHeader",
    "LogLine",
    "ProviderCapabilities",
    "ThreadCard",
    "TurnItem",
    "TurnItemBody",
];

const HEADER: &str =
    "// Generated by goat2-contracts (crates/goat2-contracts/src/codegen.rs). Do not edit.\n";

/// ts-rs settings: `number` for u64 (see [limits::MAX_SAFE_WIRE_INTEGER]), `.ts` import
/// extensions for NodeNext.
pub fn ts_config(out_dir: &Path) -> ts_rs::Config {
    ts_rs::Config::new()
        .with_large_int("number")
        .with_import_extension(Some("ts"))
        .with_out_dir(out_dir)
}

fn unique_temp_dir(kind: &str) -> Result<PathBuf, String> {
    static COUNTER: AtomicUsize = AtomicUsize::new(0);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_nanos())
        .unwrap_or_default();
    let dir = std::env::temp_dir().join(format!(
        "goat2-contracts-{kind}-{}-{}-{nanos}",
        std::process::id(),
        COUNTER.fetch_add(1, Ordering::SeqCst)
    ));
    std::fs::create_dir_all(&dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    Ok(dir)
}

/// Read every file under `dir` into `out`, keyed by `/`-separated path relative to `base`.
pub fn read_tree(base: &Path, dir: &Path, out: &mut Files) -> Result<(), String> {
    let entries = match std::fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(format!("read {}: {e}", dir.display())),
    };
    for entry in entries {
        let path = entry.map_err(|e| e.to_string())?.path();
        if path.is_dir() {
            read_tree(base, &path, out)?;
        } else {
            let rel = path
                .strip_prefix(base)
                .map_err(|e| e.to_string())?
                .components()
                .map(|c| c.as_os_str().to_string_lossy().into_owned())
                .collect::<Vec<_>>()
                .join("/");
            let text = std::fs::read_to_string(&path)
                .map_err(|e| format!("read {}: {e}", path.display()))?;
            out.insert(rel, text);
        }
    }
    Ok(())
}

fn export<T: TS + 'static>(cfg: &ts_rs::Config) -> Result<(), String> {
    T::export_all(cfg).map_err(|e| format!("ts-rs export {}: {e}", std::any::type_name::<T>()))
}

/// TypeScript for every root and its dependencies, plus `index.ts` and `limits.ts`.
pub fn render_typescript() -> Result<Files, String> {
    let dir = unique_temp_dir("ts")?;
    let cfg = ts_config(&dir);
    let result = (|| {
        export::<BotProfile>(&cfg)?;
        export::<CardFile>(&cfg)?;
        export::<ClientFrame>(&cfg)?;
        export::<Fold>(&cfg)?;
        export::<HostFrame>(&cfg)?;
        export::<LogEvent>(&cfg)?;
        export::<LogHeader>(&cfg)?;
        export::<LogLine>(&cfg)?;
        export::<ProviderCapabilities>(&cfg)?;
        export::<ThreadCard>(&cfg)?;
        export::<TurnItem>(&cfg)?;
        export::<TurnItemBody>(&cfg)?;
        let mut types = Files::new();
        read_tree(&dir, &dir, &mut types)?;
        Ok::<_, String>(types)
    })();
    let _ = std::fs::remove_dir_all(&dir);
    let types = result?;

    let mut index = String::from(HEADER);
    for rel in types.keys() {
        index.push_str(&format!("export type * from \"./{rel}\";\n"));
    }
    index.push_str("export * from \"./limits.ts\";\n");

    let mut files = Files::new();
    for (rel, text) in types {
        files.insert(format!("{TS_DIR}/{rel}"), text);
    }
    files.insert(format!("{TS_DIR}/index.ts"), index);
    files.insert(format!("{TS_DIR}/limits.ts"), render_limits());
    Ok(files)
}

/// `limits.ts`: the Rust constants and the log event type list.
pub fn render_limits() -> String {
    let mut out = String::from(HEADER);
    macro_rules! constant {
        ($($name:ident),* $(,)?) => {
            $(out.push_str(&format!("export const {} = {};\n", stringify!($name), limits::$name));)*
        };
    }
    constant!(
        LOG_FORMAT_VERSION,
        CARD_FILE_FORMAT_VERSION,
        MAX_SAFE_WIRE_INTEGER,
        CARD_TITLE_MAX_CHARS,
        NEEDS_YOU_SUMMARY_MAX_CHARS,
        CARD_EXCERPT_MAX_CHARS,
        CHILD_SUMMARY_MAX_BYTES,
        BLOB_THRESHOLD_BYTES,
        MAX_CONCURRENT_RUNS,
        MAX_CONCURRENT_STARTS,
        MAX_CHILDREN_PER_BOT,
        MAX_CHILD_DEPTH,
        ENGINE_IDLE_STOP_SECS,
        COLLECT_WINDOW_MS,
        CHILD_WAKE_COALESCE_MS,
        REPLAY_MAX_EVENTS,
        REPLAY_MAX_BYTES,
        PING_INTERVAL_SECS,
        AGENT_NICE,
        ENGINE_GROUP_MEMORY_LIMIT_BYTES,
        ENGINE_MEMORY_SAMPLE_SECS,
        ENGINE_MEMORY_WARN_PERCENT,
    );
    let tags = LogEvent::TYPE_TAGS
        .iter()
        .map(|t| format!("\"{t}\""))
        .collect::<Vec<_>>()
        .join(", ");
    out.push_str(&format!(
        "export const LOG_EVENT_TYPES = [{tags}] as const;\n"
    ));
    out
}

/// Add `maximum: 2^53-1` to every `uint64` so JSON Schema enforces the safe-integer bound.
fn safe_integer(schema: &mut Schema) {
    if let Some(obj) = schema.as_object_mut()
        && obj.get("format").and_then(|f| f.as_str()) == Some("uint64")
    {
        obj.insert("maximum".into(), limits::MAX_SAFE_WIRE_INTEGER.into());
    }
}

/// Rebuild objects with sorted keys so output does not depend on serde_json's map feature.
fn sorted(value: serde_json::Value) -> serde_json::Value {
    match value {
        serde_json::Value::Object(map) => {
            let mut entries: Vec<_> = map.into_iter().collect();
            entries.sort_by(|a, b| a.0.cmp(&b.0));
            serde_json::Value::Object(entries.into_iter().map(|(k, v)| (k, sorted(v))).collect())
        }
        serde_json::Value::Array(items) => {
            serde_json::Value::Array(items.into_iter().map(sorted).collect())
        }
        other => other,
    }
}

/// The JSON Schema (draft 2020-12, deserialize contract: what readers accept) for one type.
pub fn schema_value<T: JsonSchema>() -> serde_json::Value {
    let generator = SchemaSettings::draft2020_12()
        .with_transform(RecursiveTransform(safe_integer))
        .into_generator();
    sorted(generator.into_root_schema_for::<T>().to_value())
}

fn schema_file<T: JsonSchema>(files: &mut Files, name: &str) {
    let text = serde_json::to_string_pretty(&schema_value::<T>()).expect("schema serializes");
    files.insert(format!("{SCHEMA_DIR}/{name}.schema.json"), text + "\n");
}

/// One schema file per root in [ROOTS].
pub fn render_json_schemas() -> Files {
    let mut files = Files::new();
    schema_file::<BotProfile>(&mut files, "BotProfile");
    schema_file::<CardFile>(&mut files, "CardFile");
    schema_file::<ClientFrame>(&mut files, "ClientFrame");
    schema_file::<Fold>(&mut files, "Fold");
    schema_file::<HostFrame>(&mut files, "HostFrame");
    schema_file::<LogEvent>(&mut files, "LogEvent");
    schema_file::<LogHeader>(&mut files, "LogHeader");
    schema_file::<LogLine>(&mut files, "LogLine");
    schema_file::<ProviderCapabilities>(&mut files, "ProviderCapabilities");
    schema_file::<ThreadCard>(&mut files, "ThreadCard");
    schema_file::<TurnItem>(&mut files, "TurnItem");
    schema_file::<TurnItemBody>(&mut files, "TurnItemBody");
    files
}

/// Everything the generator owns.
pub fn render_all() -> Result<Files, String> {
    let mut files = render_typescript()?;
    files.extend(render_json_schemas());
    files.insert(FIXTURE_TS.into(), render_fixture_module(&load_fixtures()?));
    Ok(files)
}

/// Generated compile-time TypeScript checks for canonical and derived fixtures.
pub const FIXTURE_TS: &str = "packages/contracts-rs/test/fixtures.gen.ts";

/// A named JSON fixture. Names are snake_case and unique within each root.
#[derive(Debug, Clone)]
pub struct Fixture {
    pub root: String,
    pub name: String,
    pub value: serde_json::Value,
}

/// Load canonical fixtures and derive the nested root fixtures in a deterministic order.
pub fn load_fixtures() -> Result<Vec<Fixture>, String> {
    let base = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    let mut files = Files::new();
    for root in [
        "log_line",
        "log_header",
        "client_frame",
        "host_frame",
        "provider_capabilities",
        "thread_card",
        "card_file",
        "bot_profile",
    ] {
        read_tree(&base, &base.join(root), &mut files)?;
    }
    let mut fixtures = Vec::new();
    for (path, text) in files {
        let (root, file) = path
            .split_once('/')
            .ok_or_else(|| format!("invalid fixture path: {path}"))?;
        let name = file
            .strip_suffix(".json")
            .ok_or_else(|| format!("invalid fixture path: {path}"))?;
        let value: serde_json::Value =
            serde_json::from_str(&text).map_err(|e| format!("{path}: {e}"))?;
        fixtures.push(Fixture {
            root: root.into(),
            name: name.into(),
            value: value.clone(),
        });
        if root == "log_line" {
            let mut event = value.clone();
            for key in ["v", "seq", "at"] {
                event
                    .as_object_mut()
                    .ok_or("line is not an object")?
                    .remove(key);
            }
            fixtures.push(Fixture {
                root: "log_event".into(),
                name: name.into(),
                value: event,
            });
            if value["type"] == "item.completed" {
                let item = value["item"].clone();
                let mut body = item.clone();
                for key in [
                    "id",
                    "threadId",
                    "runId",
                    "providerThreadId",
                    "providerTurnId",
                    "nativeItemRef",
                    "parentItemId",
                    "ordinal",
                    "status",
                    "title",
                    "startedAt",
                    "completedAt",
                    "updatedAt",
                ] {
                    body.as_object_mut()
                        .ok_or("item is not an object")?
                        .remove(key);
                }
                fixtures.push(Fixture {
                    root: "turn_item".into(),
                    name: name.into(),
                    value: item,
                });
                fixtures.push(Fixture {
                    root: "turn_item_body".into(),
                    name: name.into(),
                    value: body,
                });
            }
            if value["type"] == "checkpoint" {
                for root in ["fold", "thread_card"] {
                    let key = if root == "fold" { "fold" } else { "card" };
                    fixtures.push(Fixture {
                        root: root.into(),
                        name: format!("checkpoint_{name}"),
                        value: value[key].clone(),
                    });
                }
            }
        }
    }
    fixtures.sort_by(|a, b| (&a.root, &a.name).cmp(&(&b.root, &b.name)));
    Ok(fixtures)
}

fn fixture_type(root: &str) -> String {
    root.split('_')
        .map(|part| {
            let mut c = part.chars();
            c.next()
                .map(|first| first.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// Render named fixture constants with TypeScript compile-time wire shape checks.
pub fn render_fixture_module(fixtures: &[Fixture]) -> String {
    let mut roots = std::collections::BTreeSet::new();
    for fixture in fixtures {
        roots.insert(fixture_type(&fixture.root));
    }
    let mut out = String::from(HEADER);
    out.push_str(&format!(
        "import type {{ {} }} from \"../src/index.ts\";\n\n",
        roots.into_iter().collect::<Vec<_>>().join(", ")
    ));
    for fixture in fixtures {
        out.push_str(&format!(
            "export const {}__{} = {} satisfies {};\n\n",
            fixture.root,
            fixture.name,
            serde_json::to_string_pretty(&fixture.value).expect("fixture JSON"),
            fixture_type(&fixture.root)
        ));
    }
    out
}
