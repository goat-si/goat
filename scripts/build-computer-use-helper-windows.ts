#!/usr/bin/env node
// Builds "GOAT Computer Use.exe", the Windows helper that runs the pinned Cua Driver as its
// child and answers GOAT's readiness and window questions from the user's session. See
// apps/desktop/native/computer-use-helper-windows/Program.cs for what it does at runtime.
//
//   node scripts/build-computer-use-helper-windows.ts --channel dev
//   $env:GOAT_CUA_HELPER_PATH = "$PWD\apps\desktop\.computer-use-helper\computer-use-helper"; vp run dev
//
// The compiler is the C# compiler every Windows 10 and 11 install ships with .NET Framework 4.8,
// so the build needs no SDK and adds no dependency. The driver's files are staged byte for byte
// as Cua signed them, and their SHA-256 is compiled into the helper, which refuses to run any
// other driver. Only the helper itself is signed here, and only with a certificate named on the
// command line; release signing through CI is a separate proposal.
import "@goat/contracts/adoptLegacyEnv";
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import {
  COMPUTER_USE_HELPER_NAME,
  computerUseHelperBundleId,
  cuaDriverRelease,
} from "@goat/shared/cuaDriverRelease";
import * as HostProcess from "@goat/shared/HostProcess";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Option from "effect/Option";
import * as Path from "effect/Path";
import { Command, Flag } from "effect/cli";

import desktopPackageJson from "../apps/desktop/package.json" with { type: "json" };
import {
  hashBytes,
  ReleaseVerificationError,
  requireReleaseCommand,
  runReleaseCommand,
  type ReleaseCommandRunner,
} from "./lib/release-verify.ts";
import { windowsSystemTar } from "./lib/windows-tar.ts";

export type HelperChannel = "stable" | "nightly" | "dev";

const CHANNEL_APP_IDS: Record<HelperChannel, string> = {
  stable: "si.goat.desktop",
  nightly: "si.goat.desktop.nightly",
  dev: "si.goat.desktop.dev",
};

/** The packaged GOAT executable a release helper accepts as its parent (resolveDesktopProductName). */
const CHANNEL_PARENTS: Record<HelperChannel, string> = {
  stable: "GOAT.exe",
  nightly: "GOAT (Nightly).exe",
  dev: "GOAT.exe",
};

/** The driver files the helper runs, staged as Cua ships them and pinned by SHA-256. */
export const PINNED_DRIVER_FILES = ["cua-driver.exe", "cua-driver-uia.exe", "cua-cursor-theme.exe"];

const csharpString = (value: string) => JSON.stringify(value);

/** The build's identity and pins, compiled into the helper. */
export function renderWindowsBuildInfo(input: {
  readonly channel: HelperChannel;
  readonly version: string;
  readonly pins: ReadonlyArray<{ readonly file: string; readonly sha256: string }>;
}): string {
  for (const pin of input.pins)
    if (!/^[0-9a-f]{64}$/u.test(pin.sha256) || !/^[\w.-]+$/u.test(pin.file))
      throw new Error("Invalid driver pin for " + pin.file + ".");
  const pins = input.pins
    .map(
      (pin) =>
        "      new KeyValuePair<string, string>(" +
        csharpString(pin.file) +
        ", " +
        csharpString(pin.sha256) +
        "),",
    )
    .join("\n");
  const numeric = (input.version.match(/^\d+\.\d+\.\d+/u)?.[0] ?? "0.0.0") + ".0";
  return [
    "// Generated by scripts/build-computer-use-helper-windows.ts.",
    "using System.Collections.Generic;",
    "using System.Reflection;",
    "[assembly: AssemblyTitle(" + csharpString(COMPUTER_USE_HELPER_NAME) + ")]",
    "[assembly: AssemblyProduct(" + csharpString(COMPUTER_USE_HELPER_NAME) + ")]",
    '[assembly: AssemblyCompany("GOAT")]',
    "[assembly: AssemblyVersion(" + csharpString(numeric) + ")]",
    "[assembly: AssemblyFileVersion(" + csharpString(numeric) + ")]",
    "[assembly: AssemblyInformationalVersion(" + csharpString(input.version) + ")]",
    "namespace Goat.ComputerUse {",
    "  internal static class BuildInfo {",
    "    public const string HelperId = " +
      csharpString(computerUseHelperBundleId(CHANNEL_APP_IDS[input.channel])) +
      ";",
    "    public const string Version = " + csharpString(input.version) + ";",
    // A dev helper serves an unpackaged Electron or a terminal; release helpers check their parent.
    "    public const bool AllowAnyParent = " + (input.channel === "dev" ? "true" : "false") + ";",
    "    public const string ParentExecutable = " +
      csharpString(CHANNEL_PARENTS[input.channel]) +
      ";",
    "    public static readonly KeyValuePair<string, string>[] PinnedFiles = {",
    pins,
    "    };",
    "  }",
    "}",
    "",
  ].join("\n");
}

/**
 * A release helper verifies its parent by Authenticode publisher, so it must be signed itself.
 * Dev helpers may stay unsigned.
 */
export function windowsSigningPlan(input: {
  readonly channel: HelperChannel;
  readonly thumbprint: string | undefined;
  readonly timestampUrl: string | undefined;
}):
  | { readonly sign: false }
  | { readonly sign: true; readonly args: ReadonlyArray<string> }
  | { readonly error: string } {
  const thumbprint = input.thumbprint?.replaceAll(/\s/gu, "").toUpperCase();
  if (!thumbprint)
    return input.channel === "dev"
      ? { sign: false }
      : {
          error:
            "A " +
            input.channel +
            " helper must be signed: pass --sign-thumbprint for a code signing certificate in this user's store.",
        };
  if (!/^[0-9A-F]{40}$/u.test(thumbprint))
    return { error: "--sign-thumbprint must be a 40 character SHA-1 thumbprint." };
  return {
    sign: true,
    args: [
      "sign",
      "/sha1",
      thumbprint,
      "/fd",
      "sha256",
      ...(input.timestampUrl ? ["/tr", input.timestampUrl, "/td", "sha256"] : []),
    ],
  };
}

const fail = (problem: string) => new ReleaseVerificationError({ problems: [problem] });

export const buildWindowsComputerUseHelper = Effect.fn("buildWindowsComputerUseHelper")(
  function* (input: {
    readonly repoRoot: string;
    readonly output: string;
    readonly channel: HelperChannel;
    readonly arch: "x64" | "arm64";
    readonly thumbprint: string | undefined;
    readonly timestampUrl: string | undefined;
    readonly runner?: ReleaseCommandRunner;
  }) {
    const fs = yield* FileSystem.FileSystem;
    const path = yield* Path.Path;
    const run = (program: string, args: readonly string[]) =>
      requireReleaseCommand(input.runner ?? runReleaseCommand, program, args);
    if ((yield* HostProcess.Platform) !== "win32")
      return yield* fail("The Windows helper builds on Windows only.");
    const signing = windowsSigningPlan(input);
    if ("error" in signing) return yield* fail(signing.error);

    const release = cuaDriverRelease("win32", input.arch);
    if (!release)
      return yield* fail("No pinned Cua Driver release for Windows " + input.arch + ".");
    // Same cache and pin as the desktop artifact build.
    const cacheDir = path.join(input.repoRoot, "node_modules/.cache/goat/cua-driver");
    const archive = path.join(cacheDir, release.archiveName);
    const verified = Effect.fn("verifyCuaDriverArchive")(function* () {
      if (!(yield* fs.exists(archive))) return false;
      const bytes = yield* fs.readFile(archive);
      return (
        bytes.length === release.bytes && (yield* hashBytes(bytes, "SHA-256")) === release.sha256
      );
    });
    yield* fs.makeDirectory(cacheDir, { recursive: true });
    if (!(yield* verified())) {
      yield* run("curl.exe", [
        "--fail",
        "--location",
        "--silent",
        "--show-error",
        "--retry",
        "3",
        "--output",
        archive,
        release.url,
      ]);
      if (!(yield* verified()))
        return yield* fail(
          "Cua Driver archive failed size/SHA-256 verification: " + release.archiveName,
        );
    }

    const work = yield* fs.makeTempDirectoryScoped({ prefix: "goat-computer-use-" });
    const extracted = path.join(work, "driver");
    yield* fs.makeDirectory(extracted);
    yield* run(windowsSystemTar(), ["-xf", archive, "-C", extracted]);

    const helperDir = path.join(input.output, "computer-use-helper");
    const driverDir = path.join(helperDir, "cua-driver");
    const noticesDir = path.join(helperDir, "notices");
    yield* fs.remove(helperDir, { recursive: true, force: true });
    for (const directory of [driverDir, noticesDir])
      yield* fs.makeDirectory(directory, { recursive: true });
    const pins: Array<{ file: string; sha256: string }> = [];
    for (const file of PINNED_DRIVER_FILES) {
      const source = path.join(extracted, file);
      if (!(yield* fs.exists(source)))
        return yield* fail("Cua Driver release is missing " + file + ".");
      const bytes = yield* fs.readFile(source);
      yield* fs.writeFile(path.join(driverDir, file), bytes);
      pins.push({ file, sha256: yield* hashBytes(bytes, "SHA-256") });
    }

    const sourceDir = path.join(input.repoRoot, "apps/desktop/native/computer-use-helper-windows");
    const buildInfo = path.join(work, "BuildInfo.g.cs");
    yield* fs.writeFileString(
      buildInfo,
      renderWindowsBuildInfo({ channel: input.channel, version: desktopPackageJson.version, pins }),
    );
    const framework = path.join(
      process.env.WINDIR ?? "C:\\Windows",
      "Microsoft.NET",
      "Framework64",
      "v4.0.30319",
    );
    const sources = (yield* fs.readDirectory(sourceDir))
      .filter((name) => name.endsWith(".cs"))
      .map((name) => path.join(sourceDir, name));
    const executable = path.join(helperDir, COMPUTER_USE_HELPER_NAME + ".exe");
    yield* run(path.join(framework, "csc.exe"), [
      "/nologo",
      "/target:exe",
      // AnyCPU runs natively on x64, and on Arm64 under .NET Framework 4.8.1.
      "/platform:anycpu",
      "/optimize+",
      "/warnaserror+",
      "/win32manifest:" + path.join(sourceDir, "app.manifest"),
      "/out:" + executable,
      "/r:" + path.join(framework, "WPF", "UIAutomationClient.dll"),
      "/r:" + path.join(framework, "WPF", "UIAutomationTypes.dll"),
      "/r:" + path.join(framework, "WPF", "WindowsBase.dll"),
      "/r:" + path.join(framework, "System.Web.Extensions.dll"),
      ...sources,
      buildInfo,
    ]);
    // Cua Driver's MIT notices travel with every copy of the driver (#667).
    const notices = path.join(input.repoRoot, "apps/desktop/src/cua/notices");
    for (const name of yield* fs.readDirectory(notices))
      yield* fs.copyFile(path.join(notices, name), path.join(noticesDir, name));
    if (signing.sign) {
      yield* run("signtool.exe", [...signing.args, executable]);
      yield* run("signtool.exe", ["verify", "/pa", executable]);
    }
    return { helperDir, executable, signed: signing.sign };
  },
  Effect.scoped,
);

const command = Command.make(
  "build-computer-use-helper-windows",
  {
    channel: Flag.Literals("channel", ["dev", "nightly", "stable"]).pipe(Flag.withDefault("dev")),
    arch: Flag.Literals("arch", ["x64", "arm64"]).pipe(Flag.withDefault("x64")),
    output: Flag.String("output").pipe(Flag.optional),
    signThumbprint: Flag.String("sign-thumbprint").pipe(
      Flag.withDescription("SHA-1 thumbprint of a code signing certificate for signtool."),
      Flag.optional,
    ),
    timestampUrl: Flag.String("timestamp-url").pipe(
      Flag.withDescription("RFC 3161 timestamp server for signtool."),
      Flag.optional,
    ),
  },
  ({ channel, arch, output, signThumbprint, timestampUrl }) =>
    Effect.gen(function* () {
      const path = yield* Path.Path;
      const repoRoot = path.resolve(import.meta.dirname, "..");
      const built = yield* buildWindowsComputerUseHelper({
        repoRoot,
        channel,
        arch,
        output: Option.getOrElse(output, () =>
          path.join(repoRoot, "apps/desktop/.computer-use-helper"),
        ),
        thumbprint: Option.getOrUndefined(signThumbprint),
        timestampUrl: Option.getOrUndefined(timestampUrl),
      });
      yield* Effect.log(
        "Built " + built.executable + (built.signed ? " (signed)." : " (unsigned dev build)."),
      );
    }),
);
if (import.meta.main)
  Command.run(command, { version: "0.0.0" }).pipe(
    Effect.provide(NodeServices.layer),
    NodeRuntime.runMain,
  );
