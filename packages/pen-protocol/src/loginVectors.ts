import { nodeIdFromSignPub, signingKeyFromSeed, toHex, x25519PublicKey } from "./identity.ts";
import {
  type Assertion,
  type AssertionBody,
  assertionHash,
  base64url,
  forgetProofMessage,
  fromBase64url,
  loginKid,
  pollProofMessage,
  registerProofMessage,
  signAssertion,
  startProofMessage,
} from "./login.ts";

// Byte fields named *Seed, *Priv and message are hex; keys, codes, proofs and assertion parts are base64url.
const NODE_SEED = new Uint8Array(32).fill(0x41);
const NOISE_PRIV = new Uint8Array(32).fill(0x42);
const LOGIN_SEED = new Uint8Array(32).fill(0x4c);
const OTHER_LOGIN_SEED = new Uint8Array(32).fill(0x4d);
const DEVICE_CODE = Uint8Array.from({ length: 32 }, (_, i) => 0xa0 + i);
const LOGIN_URL = "https://pen-login.pos090001.workers.dev";
const IAT = 1_794_300_000;
const FORGET_TS = 1_794_300_000_123;

export async function buildLoginVector() {
  const node = await signingKeyFromSeed(NODE_SEED);
  const noisePub = await x25519PublicKey(NOISE_PRIV);
  const nodeId = await nodeIdFromSignPub(node.signPub);
  const loginKey = await signingKeyFromSeed(LOGIN_SEED);
  const kid = await loginKid(loginKey.signPub);
  const other = await signingKeyFromSeed(OTHER_LOGIN_SEED);
  const name = "box-1";

  const startMessage = startProofMessage(node.signPub, noisePub, name);
  const pollMessage = pollProofMessage(DEVICE_CODE);
  const forgetMessage = forgetProofMessage(nodeId, FORGET_TS);

  const body: AssertionBody = {
    v: 1,
    iss: LOGIN_URL,
    kid,
    sub: "112233445566778899000",
    email: "person@example.com",
    signPub: base64url(node.signPub),
    noisePub: base64url(noisePub),
    iat: IAT,
    exp: IAT + 600,
  };
  const assertion = await signAssertion(body, loginKey);
  const meshId = "aaaaaaaaaaaaaaaaaaaaaaaaaa";
  const registerMessage = await registerProofMessage(fromBase64url(assertion.body), meshId);
  const member = {
    iss: LOGIN_URL,
    sub: body.sub,
    signPub: body.signPub,
    noisePub: body.noisePub,
    skew: 60,
  };
  const at = (now: number) => ({ ...member, now });
  const otherKeyBody = { ...body, kid: await loginKid(other.signPub) };
  const tampered: Assertion = {
    body: assertion.body,
    sig: (await signAssertion({ ...body, sub: "1" }, loginKey)).sig,
  };
  const checks = [
    { name: "valid at iat", assertion, context: at(IAT), ok: true, reason: null },
    {
      name: "valid 59 s after exp (skew)",
      assertion,
      context: at(IAT + 600 + 59),
      ok: true,
      reason: null,
    },
    {
      name: "valid 60 s before iat (skew)",
      assertion,
      context: at(IAT - 60),
      ok: true,
      reason: null,
    },
    {
      name: "expired 60 s after exp",
      assertion,
      context: at(IAT + 660),
      ok: false,
      reason: "expired",
    },
    {
      name: "issued 61 s in the future",
      assertion,
      context: at(IAT - 61),
      ok: false,
      reason: "not_yet_valid",
    },
    {
      name: "signature over another body",
      assertion: tampered,
      context: at(IAT),
      ok: false,
      reason: "bad_signature",
    },
    {
      name: "signed by a key that is not the binding's",
      assertion: await signAssertion(otherKeyBody, other),
      context: at(IAT),
      ok: false,
      reason: "unknown_kid",
    },
    {
      name: "iss is not the binding's loginUrl",
      assertion,
      context: { ...at(IAT), iss: "https://pen-login.example" },
      ok: false,
      reason: "wrong_iss",
    },
    {
      name: "sub is not the binding's",
      assertion,
      context: { ...at(IAT), sub: "999" },
      ok: false,
      reason: "wrong_sub",
    },
    {
      name: "card noisePub differs from the assertion's",
      assertion,
      context: { ...at(IAT), noisePub: base64url(new Uint8Array(32)) },
      ok: false,
      reason: "key_mismatch",
    },
    {
      name: "lifetime over 600 s",
      assertion: await signAssertion({ ...body, exp: IAT + 601 }, loginKey),
      context: at(IAT),
      ok: false,
      reason: "malformed",
    },
  ];

  return {
    description:
      "Pen v1.1 login vectors (contract Accounts). Generated by TS: node packages/pen-protocol/scripts/vectors.ts. Seeds and messages are hex; keys, the device code, proofs and assertion parts are base64url without padding. Check contexts use Unix seconds and the member skew of 60 s.",
    node: {
      signSeed: toHex(NODE_SEED),
      noisePriv: toHex(NOISE_PRIV),
      signPub: base64url(node.signPub),
      noisePub: base64url(noisePub),
      nodeId,
      name,
    },
    loginKey: { seed: toHex(LOGIN_SEED), pub: base64url(loginKey.signPub), kid },
    start: { name, message: toHex(startMessage), proof: base64url(await node.sign(startMessage)) },
    poll: {
      deviceCode: base64url(DEVICE_CODE),
      message: toHex(pollMessage),
      proof: base64url(await node.sign(pollMessage)),
    },
    forget: {
      nodeId,
      ts: FORGET_TS,
      message: toHex(forgetMessage),
      proof: base64url(await node.sign(forgetMessage)),
    },
    register: {
      meshId,
      message: toHex(registerMessage),
      proof: base64url(await node.sign(registerMessage)),
    },
    assertion: {
      bodyJson: new TextDecoder().decode(fromBase64url(assertion.body)),
      body: assertion.body,
      sig: assertion.sig,
      hash: await assertionHash(assertion),
    },
    checks,
  };
}
