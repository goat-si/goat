var updateStream = flag.Bool("update-stream", false, "rewrite packages/pen-protocol/vectors/stream.json")

const streamVectors = "../../../../packages/pen-protocol/vectors/stream.json"

type streamRecord struct {
	Meaning string `json:"meaning"`
	Hex     string `json:"hex"`
}

// streamReject is a sequence of records a receiver must refuse with code, after Fill DATA records of FillSize
// zero bytes each when Fill is set.
type streamReject struct {
	Why      string   `json:"why"`
	Records  []string `json:"records"`
	Fill     int      `json:"fill,omitempty"`
	FillSize int      `json:"fillSize,omitempty"`
	Code     uint16   `json:"code"`
}

type streamFile struct {
	Note        string         `json:"note"`
	MaxData     int            `json:"maxData"`
	Window      int            `json:"window"`
	CreditEvery int            `json:"creditEvery"`
	Records     []streamRecord `json:"records"`
	Reject      []streamReject `json:"reject"`
}

func credit(n uint32) []byte {
	rec := []byte{stream.TypeCredit, 0, 0, 0, 0}
	binary.LittleEndian.PutUint32(rec[1:], n)
	return rec
}

func buildStreamVectors() streamFile {
	h := hex.EncodeToString
	return streamFile{
		Note: "Pen tcp framing (contract \"Streams\"), also used by service and service-pair streams. Generated by Go: " +
			"go test ./internal/stream -run TestStreamVectors -update-stream. Each record is one Noise plaintext. A reject " +
			"case is sent in order on a fresh stream to a receiver that has sent nothing and consumes nothing; it must close " +
			"with code.",
		MaxData: stream.MaxData, Window: stream.Window, CreditEvery: stream.CreditEvery,
		Records: []streamRecord{
			{"DATA \"hello\"", h(append([]byte{stream.TypeData}, "hello"...))},
			{"DATA with no bytes", h([]byte{stream.TypeData})},
			{"FIN", h([]byte{stream.TypeFin})},
			{"CREDIT 65536 (u32 little-endian)", h(credit(65536))},
		},
		Reject: []streamReject{
			{Why: "an empty record", Records: []string{""}, Code: wire.CodeCrypto},
			{Why: "an unknown type", Records: []string{"03"}, Code: wire.CodeCrypto},
			{Why: "FIN with a byte", Records: []string{"0100"}, Code: wire.CodeCrypto},
			{Why: "a second FIN", Records: []string{"01", "01"}, Code: wire.CodeCrypto},
			{Why: "DATA after FIN", Records: []string{"01", "0061"}, Code: wire.CodeCrypto},
			{Why: "CREDIT of 3 bytes", Records: []string{"02000001"}, Code: wire.CodeCrypto},
			{Why: "CREDIT of 5 bytes", Records: []string{"020000010000"}, Code: wire.CodeCrypto},
			{Why: "CREDIT for more than was sent", Records: []string{h(credit(1))}, Code: wire.CodeCrypto},
			{Why: "DATA past the window", Fill: 9, FillSize: stream.MaxData, Code: wire.CodeTimeout},
		},
	}
}

// refusedWith runs one reject case against Splice and returns the code it closed with.
func refusedWith(t *testing.T, c streamReject) uint16 {
	t.Helper()
	near, far := relay.Pipe()
	// Neither side sends or consumes: r and w block, so no FIN and no CREDIT leaves this end.
	in, unused := io.Pipe()
	stalled, out := io.Pipe()
	defer in.Close()
	defer unused.Close()
	defer stalled.Close()
	defer out.Close()
	done := make(chan error, 1)
	go func() { done <- stream.Splice(context.Background(), near, in, out, nil) }()
	var recs [][]byte
	for range c.Fill {
		recs = append(recs, append([]byte{stream.TypeData}, make([]byte, c.FillSize)...))
	}
	for _, r := range c.Records {
		b, err := hex.DecodeString(r)
		if err != nil {
			t.Fatal(err)
		}
		recs = append(recs, b)
	}
	for _, r := range recs {
		if far.Send(r) != nil {
			break
		}
	}
	return relay.CodeOf(<-done)
}

func TestStreamVectors(t *testing.T) {
	got := buildStreamVectors()
	if *updateStream {
		b, _ := json.MarshalIndent(got, "", "  ")
		if err := os.WriteFile(streamVectors, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(streamVectors)
	if err != nil {
		t.Fatal(err)
	}
	var want streamFile
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatal("stream.json does not match the implementation")
	}
	for _, c := range want.Reject {
		if code := refusedWith(t, c); code != c.Code {
			t.Errorf("%s: closed %d, want %d", c.Why, code, c.Code)
		}
	}
	if !bytes.Equal(credit(65536), []byte{2, 0, 0, 1, 0}) {
		t.Fatal("CREDIT is not little-endian")
	}
}
