var updatePair = flag.Bool("update-pair", false, "rewrite packages/pen-protocol/vectors/servicepair.json")

const pairVectors = "../../../../packages/pen-protocol/vectors/servicepair.json"

// codeCase is the first 8 bytes of a sas and the code they give.
type codeCase struct {
	SASPrefix string `json:"sasPrefix"`
	Code      string `json:"code"`
}

type pairFile struct {
	Note       string     `json:"note"`
	Encoding   string     `json:"encoding"`
	Node       keyVector  `json:"node"`
	Phone      keyVector  `json:"phone"`
	Name       string     `json:"name"`
	Secret     string     `json:"secret"`
	InviteID   string     `json:"inviteId"`
	PSK        string     `json:"psk"`
	Transcript transcript `json:"transcript"`
	SAS        string     `json:"sas"`
	SASText    string     `json:"sasText"`
	Code       string     `json:"code"`
	Codes      []codeCase `json:"codes"`
}

// The program side of a service invite (contract "Service invites"): the node never derives these, it receives
// I and P, so they live with the vectors.
func serviceInviteID(secret []byte) string {
	sum := sha256.Sum256(append([]byte("pen/1 service invite"), secret...))
	return ident.B64.EncodeToString(sum[:12])
}

func servicePSK(t *testing.T, secret []byte, nodeID string, noisePub []byte, name string) []byte {
	info := append(append([]byte("pen/1 service psk"+nodeID), noisePub...), name...)
	psk, err := hkdf.Key(sha256.New, secret, nil, string(info), 32)
	if err != nil {
		t.Fatal(err)
	}
	return psk
}

func pairCode(sas []byte) string {
	return fmt.Sprintf("%06d", binary.BigEndian.Uint64(sas[:8])%1_000_000)
}

func buildPairVectors(t *testing.T) pairFile {
	node, nv := fixedID(t, 0x11, 0x22)
	phone, pv := fixedID(t, 0x33, 0x44)
	secret := bytes.Repeat([]byte{0x5a}, 32)
	name := "goat"
	id := serviceInviteID(secret)
	psk := servicePSK(t, secret, node.NodeID(), node.NoisePub, name)
	tr := run(t, KindJoin, node, phone, psk, Payload{V: 1, Stream: "service-pair", Invite: id, Name: name},
		bytes.Repeat([]byte{0xaa}, 32), bytes.Repeat([]byte{0xbb}, 32))
	if replayed := handshakeHash(t, KindJoin, node, phone, psk, tr); replayed != tr.HandshakeHash {
		t.Fatalf("offline replay h %s, live h %s", replayed, tr.HandshakeHash)
	}
	h, _ := hex.DecodeString(tr.HandshakeHash)
	sas := PairSAS(h)
	f := pairFile{
		Note: "Pen v1.3 service invite (contract \"Service invites\"). Generated by Go with flynn/noise: " +
			"go test ./internal/session -run TestServicePairVectors -update-pair. The node is the responder, the phone the " +
			"initiator; message1 starts with the kind byte; handshakeHash is h after message 2, equal at both ends. " +
			"codes: the first 8 bytes of a sas and the code they give.",
		Encoding: "hex for bytes; base64url (no padding) for signPub, noisePub, inviteId and sasText; payloads are UTF-8",
		Node:     nv, Phone: pv, Name: name,
		Secret: hex.EncodeToString(secret), InviteID: id, PSK: hex.EncodeToString(psk),
		Transcript: tr, SAS: hex.EncodeToString(sas), SASText: ident.B64.EncodeToString(sas), Code: pairCode(sas),
	}
	for _, prefix := range []string{"0000000000000000", "ffffffffffffffff", "00000000000f426a", "00000000000f423f", "8000000000000000"} {
		b, _ := hex.DecodeString(prefix)
		f.Codes = append(f.Codes, codeCase{SASPrefix: prefix, Code: pairCode(append(b, make([]byte, 24)...))})
	}
	return f
}

func TestServicePairVectors(t *testing.T) {
	got := buildPairVectors(t)
	if *updatePair {
		b, _ := json.MarshalIndent(got, "", "  ")
		if err := os.WriteFile(pairVectors, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(pairVectors)
	if err != nil {
		t.Fatal(err)
	}
	var want pairFile
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatal("servicepair.json does not match the implementation")
	}
}
