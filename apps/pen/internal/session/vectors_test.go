type keyVector struct {
	SignSeed  string `json:"signSeed"`
	NoisePriv string `json:"noisePriv"`
	SignPub   string `json:"signPub"`
	NoisePub  string `json:"noisePub"`
	NodeID    string `json:"nodeId"`
}

type transcript struct {
	Kind              int    `json:"kind"`
	Prologue          string `json:"prologue"`
	PSK               string `json:"psk,omitempty"`
	InitiatorEphPriv  string `json:"initiatorEphemeralPriv"`
	ResponderEphPriv  string `json:"responderEphemeralPriv"`
	Payload1          string `json:"payload1"`
	Message1          string `json:"message1"`
	Payload2          string `json:"payload2"`
	Message2          string `json:"message2"`
	HandshakeHash     string `json:"handshakeHash"`
	KeyConfirmation   string `json:"keyConfirmation"`
	InitiatorRecordPT string `json:"initiatorRecordPlaintext"`
	InitiatorRecord   string `json:"initiatorRecord"`
	ResponderRecordPT string `json:"responderRecordPlaintext"`
	ResponderRecord   string `json:"responderRecord"`
}

type sessionFile struct {
	Description  string     `json:"description"`
	Encoding     string     `json:"encoding"`
	Responder    keyVector  `json:"responder"`
	Initiator    keyVector  `json:"initiator"`
	InviteSecret string     `json:"inviteSecret"`
	InviteID     string     `json:"inviteId"`
	JoinPSK      string     `json:"joinPsk"`
	IK           transcript `json:"ik"`
	IKpsk2       transcript `json:"ikpsk2"`
}

func fixedID(t *testing.T, seed, noise byte) (*ident.Identity, keyVector) {
	s, n := bytes.Repeat([]byte{seed}, 32), bytes.Repeat([]byte{noise}, 32)
	id, err := ident.FromSeeds(s, n)
	if err != nil {
		t.Fatal(err)
	}
	return id, keyVector{hex.EncodeToString(s), hex.EncodeToString(n), ident.B64.EncodeToString(id.SignPub), ident.B64.EncodeToString(id.NoisePub), id.NodeID()}
}

// recorder captures every message one side sends.
type recorder struct {
	relay.Conn
	sent [][]byte
}

func (r *recorder) Send(p []byte) error {
	r.sent = append(r.sent, append([]byte(nil), p...))
	return r.Conn.Send(p)
}

func run(t *testing.T, kind byte, resp, init *ident.Identity, psk []byte, payload Payload, ie, re []byte) transcript {
	t.Helper()
	ctx := context.Background()
	a, b := relay.Pipe()
	ra, rb := &recorder{Conn: a}, &recorder{Conn: b}
	rc := make(chan *Secure, 1)
	go func() {
		s, err := respond(ctx, rb, resp, resp.NodeID(), func(byte, []byte, Payload) ([]byte, error) { return psk, nil }, bytes.NewReader(re))
		if err != nil {
			t.Error(err)
		}
		rc <- s
	}()
	is, err := initiate(ctx, ra, kind, resp.NodeID(), resp.NoisePub, init, psk, payload, bytes.NewReader(ie))
	if err != nil {
		t.Fatal(err)
	}
	rs := <-rc
	if !bytes.Equal(is.HandshakeHash, rs.HandshakeHash) || len(is.HandshakeHash) != 32 {
		t.Fatalf("handshake hash: initiator %x, responder %x", is.HandshakeHash, rs.HandshakeHash)
	}
	ipt, rpt := []byte("ping from the initiator"), []byte("pong from the responder")
	is.Send(ipt)
	if got, err := rs.Recv(ctx); err != nil || !bytes.Equal(got, ipt) {
		t.Fatal("initiator record", err)
	}
	rs.Send(rpt)
	if got, err := is.Recv(ctx); err != nil || !bytes.Equal(got, rpt) {
		t.Fatal("responder record", err)
	}
	line, _ := EncodePayload(payload)
	tr := transcript{
		Kind: int(kind), Prologue: hex.EncodeToString(Prologue(resp.NodeID(), kind)),
		InitiatorEphPriv: hex.EncodeToString(ie), ResponderEphPriv: hex.EncodeToString(re),
		Payload1: string(line), Message1: hex.EncodeToString(ra.sent[0]),
		Payload2: string(msg2Payload), Message2: hex.EncodeToString(rb.sent[0]),
		KeyConfirmation:   hex.EncodeToString(ra.sent[1]),
		InitiatorRecordPT: string(ipt), InitiatorRecord: hex.EncodeToString(ra.sent[2]),
		ResponderRecordPT: string(rpt), ResponderRecord: hex.EncodeToString(rb.sent[1]),
		HandshakeHash: hex.EncodeToString(rs.HandshakeHash),
	}
	if kind == KindJoin {
		tr.PSK = hex.EncodeToString(psk)
	}
	return tr
}

func buildSessionVectors(t *testing.T) sessionFile {
	resp, rv := fixedID(t, 0x11, 0x22)
	init, iv := fixedID(t, 0x33, 0x44)
	secret := bytes.Repeat([]byte{0x55}, 32)
	psk, err := JoinPSK(secret, resp.NodeID(), resp.NoisePub)
	if err != nil {
		t.Fatal(err)
	}
	f := sessionFile{
		Description: "Pen v1.0 Noise vectors (contract Sessions/Record layer). Generated by Go with flynn/noise: " +
			"go test ./internal/session -run TestSessionVectors -update. message1 starts with the kind byte. " +
			"Ephemeral private keys are fixed; records are ChaCha20-Poly1305 with nonces 0 (key confirmation) and 1.",
		Encoding:  "hex for bytes; base64url (no padding) for signPub/noisePub; payloads are UTF-8 strings",
		Responder: rv, Initiator: iv,
		InviteSecret: hex.EncodeToString(secret), InviteID: InviteID(secret), JoinPSK: hex.EncodeToString(psk),
	}
	f.IK = run(t, KindSession, resp, init, nil, Payload{V: 1, Stream: "tcp", Port: 22},
		bytes.Repeat([]byte{0x66}, 32), bytes.Repeat([]byte{0x77}, 32))
	f.IKpsk2 = run(t, KindJoin, resp, init, psk, Payload{V: 1, Stream: "join", Invite: InviteID(secret), Name: "joiner"},
		bytes.Repeat([]byte{0x88}, 32), bytes.Repeat([]byte{0x99}, 32))
	f.IK.HandshakeHash = handshakeHash(t, KindSession, resp, init, nil, f.IK)
	f.IKpsk2.HandshakeHash = handshakeHash(t, KindJoin, resp, init, psk, f.IKpsk2)
	return f
}

// handshakeHash replays the initiator side offline to read h after message 2.
func handshakeHash(t *testing.T, kind byte, resp, init *ident.Identity, psk []byte, tr transcript) string {
	ie, _ := hex.DecodeString(tr.InitiatorEphPriv)
	hs, err := newHS(kind, resp, init, psk, ie)
	if err != nil {
		t.Fatal(err)
	}
	if _, _, _, err := hs.WriteMessage(nil, []byte(tr.Payload1)); err != nil {
		t.Fatal(err)
	}
	m2, _ := hex.DecodeString(tr.Message2)
	if _, _, _, err := hs.ReadMessage(nil, m2); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(hs.ChannelBinding())
}

func TestSessionVectors(t *testing.T) {
	got := buildSessionVectors(t)
	if *update {
		b, _ := json.MarshalIndent(got, "", "  ")
		if err := os.WriteFile(sessionVectors, append(b, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	raw, err := os.ReadFile(sessionVectors)
	if err != nil {
		t.Fatal(err)
	}
	var want sessionFile
	if err := json.Unmarshal(raw, &want); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatal("session.json does not match the implementation")
	}
}
